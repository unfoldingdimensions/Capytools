/**
 * LICENSE -> src/lib/capytools/license-text.ts
 *
 * /license used to read the repo's LICENSE with readFileSync at module scope.
 * That worked on a Node server and fails on Cloudflare Workers, where there is
 * no filesystem: the page 500s with ENOENT /bundle/LICENSE. The comment said
 * "at build time", but module scope is evaluated when the worker imports the
 * route — at request time.
 *
 * So the read moves to an actual build step. LICENSE stays the one canonical
 * text (GitHub needs it at the repo root anyway) and this emits it as a module
 * the bundler can carry. `prebuild` runs it, so it cannot drift locally, and
 * the generated file is committed so a clean checkout builds without it.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = process.cwd();
const license = readFileSync(join(root, "LICENSE"), "utf8");

const out = `// GENERATED by scripts/generate-license-text.mjs — do not edit.
// Source of truth is the repo's LICENSE file; run \`npm run build\` to refresh.
export const LICENSE_TEXT = ${JSON.stringify(license)};
`;

const target = join(root, "src", "lib", "capytools", "license-text.ts");
writeFileSync(target, out, "utf8");
console.log(`license-text.ts written (${license.length} chars)`);
