    // The warm cell maps to the cool entry and flips; the two cool cells map to
    // the same cool entry and don't; the black cell is near-neutral, skipped.
    expect(hueFlipRate(cells, Uint8Array.from([0, 0, 0, 0]), palette, 4)).toBeCloseTo(1 / 3, 9);
