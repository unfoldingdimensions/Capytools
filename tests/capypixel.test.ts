/** Diagonal gradient with a hue cross-current. */
function gradientCells(cols: number, rows: number): Uint8Array {
  const n = cols * rows;
  const cells = new Uint8Array(n * 3);
  for (let y = 0; y < rows; y++) {
    for (let x = 0; x < cols; x++) {
      const i = y * cols + x;
      const t = x / (cols - 1);
      const u = y / (rows - 1);
      cells[i * 3] = Math.round(18 + 220 * t);
      cells[i * 3 + 1] = Math.round(24 + 180 * (1 - u));
      cells[i * 3 + 2] = Math.round(140 - 90 * t + 80 * u);
    }
  }
  return cells;
}

/**
 * A "portrait-ish" frame: dark navy backdrop, a lit gold drape in two folds, a
 * blue floor — flat regions with a few transitions, so flatness can tell 1-bit
 * art from a halftone screen.
 */
function portraitCells(cols: number, rows: number): Uint8Array {
  const n = cols * rows;
  const cells = new Uint8Array(n * 3);
  for (let y = 0; y < rows; y++) {
    for (let x = 0; x < cols; x++) {
      const i = y * cols + x;
      let r: number;
      let g: number;
      let b: number;
      if (y < rows * 0.3) {
        r = 16;
        g = 20;
        b = 34; // dark backdrop, below the black point
      } else if (y < rows * 0.48) {
        r = 190;
        g = 140;
        b = 60; // lit gold drape, bright enough to snap solid
      } else if (y < rows * 0.68) {
        r = 170;
        g = 125;
        b = 55; // drape, lower fold
      } else {
        r = 26;
        g = 36;
        b = 62; // blue floor, dark enough to go solid
      }
      cells[i * 3] = r;
      cells[i * 3 + 1] = g;
      cells[i * 3 + 2] = b;
    }
  }
  return cells;
}

function rampCells(cols: number, rows: number): Uint8Array {
  const n = cols * rows;
  const cells = new Uint8Array(n * 3);
  for (let i = 0; i < n; i++) {
    const v = Math.round((i / (n - 1)) * 255);
    cells[i * 3] = v;
    cells[i * 3 + 1] = v;
    cells[i * 3 + 2] = v;
  }
  return cells;
}

