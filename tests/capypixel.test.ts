describe("determinism — same input, byte-identical indices, per preset", () => {
  for (const id of STYLE_ORDER) {
    it(`${id} quantizes identically twice`, () => {
      const usePortrait = id === "1bit" || id === "1bit-halftone";
      const cells = usePortrait ? portraitCells(24, 24) : gradientCells(8, 8);
      const dim = usePortrait ? 24 : 8;
      const p = presetParams(id);
      const a = run(cells, dim, dim, p);
      const b = run(cells, dim, dim, p);
      expect(disagreement(a.indices, b.indices)).toBe(0);
      expect(Array.from(a.indices)).toEqual(Array.from(b.indices));
    });
  }

  it("floyd and none modes are deterministic too", () => {
    const cells = gradientCells(16, 16);
    for (const dither of ["floyd", "none"] as const) {
      const p = { ...presetParams("faithful"), dither };
      const a = run(cells, 16, 16, p);
      const b = run(cells, 16, 16, p);
      expect(disagreement(a.indices, b.indices)).toBe(0);
    }
  });
});

