describe("1-bit flatness — the guard against reintroducing the halftone bug", () => {
  it("the portrait fixture through the 1bit preset scores flatness ≥ 0.8", () => {
    const cells = portraitCells(24, 24);
    const got = run(cells, 24, 24, presetParams("1bit"));
    expect(got.metrics.flatness).toBeGreaterThanOrEqual(0.8);
  });

  it("the contrast-modulated bias snaps decisive tones solid and dithers only mid-bracket", () => {
    const plab = FIXED_PALETTES["1bit"].map((p) => oklab(p[0], p[1], p[2])) as Array<[number, number, number]>;
    const br = bracketTable(plab);
    // Near an entry: zero bias — the cell snaps solid.
    expect(ditherBias(0.05, br, 0, 0, 1, 0.35)).toBe(0);
    // Mid-bracket: the Bayer bias, scaled to the bracket.
    const mid = ditherBias(0.5, br, 0, 0, 1, 0.35);
    expect(Math.abs(mid)).toBeGreaterThan(0);
    // Band 0 disables dithering; band 1 keeps dithering tones that band 0.35
    // has already released to solid (the snap at L 0.8).
    expect(ditherBias(0.5, br, 0, 0, 1, 0)).toBe(0);
    expect(ditherBias(0.8, br, 0, 0, 1, 0.35)).toBe(0);
    expect(Math.abs(ditherBias(0.8, br, 0, 0, 1, 1))).toBeGreaterThan(0);
    // The bias lives in the palette's own luminance spacing.
    expect(lRange(plab as Array<[number, number, number]>)).toBeCloseTo(1, 6);
    expect(bayer(0, 0)).toBeCloseTo(-0.5 + 0, 12);
  });
});

